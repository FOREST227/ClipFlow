import AppKit
import XCTest
@testable import ClipFlowApp

@MainActor
final class SensitiveCaptureTests: XCTestCase {
    private func fixture() throws -> (URL, UserDefaults) {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let suite = "ClipFlowTests.\(UUID().uuidString)"
        let defaults = try XCTUnwrap(UserDefaults(suiteName: suite))
        addTeardownBlock {
            defaults.removePersistentDomain(forName: suite)
            try? FileManager.default.removeItem(at: directory)
        }
        return (directory, defaults)
    }

    private func declare(_ text: String, marker: NSPasteboard.PasteboardType?, on pasteboard: NSPasteboard) {
        var types: [NSPasteboard.PasteboardType] = [.string]
        if let marker {
            types.append(marker)
        }
        pasteboard.declareTypes(types, owner: nil)
        XCTAssertTrue(pasteboard.setString(text, forType: .string))
        if let marker {
            XCTAssertTrue(pasteboard.setData(Data(), forType: marker))
        }
    }

    func testMarkerDetectionMatchesOnlySensitiveTypes() {
        XCTAssertFalse(SensitivePasteboard.containsMarker(in: nil))
        XCTAssertFalse(SensitivePasteboard.containsMarker(in: []))
        XCTAssertFalse(SensitivePasteboard.containsMarker(in: [.string]))
        XCTAssertFalse(SensitivePasteboard.containsMarker(in: [NSPasteboard.PasteboardType("com.example.custom")]))

        for marker in SensitivePasteboard.markerTypes {
            XCTAssertTrue(SensitivePasteboard.containsMarker(in: [marker]), marker.rawValue)
            XCTAssertTrue(SensitivePasteboard.containsMarker(in: [.string, marker]), marker.rawValue)
        }

        XCTAssertTrue(SensitivePasteboard.markerTypes.contains(SensitivePasteboard.concealedType))
        XCTAssertTrue(SensitivePasteboard.markerTypes.contains(SensitivePasteboard.transientType))
        XCTAssertTrue(SensitivePasteboard.markerTypes.contains(SensitivePasteboard.autoGeneratedType))
        XCTAssertTrue(SensitivePasteboard.markerTypes.contains(SensitivePasteboard.autoGeneratedTypeMisspelling))
    }

    func testSensitiveMarkersSkipCaptureWithoutBlockingTheNextCopy() throws {
        let (directory, defaults) = try fixture()
        let store = ClipFlowStore(storageDirectory: directory, defaults: defaults)
        defer { store.flushPendingPersistenceForTests() }
        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let monitor = ClipboardMonitor(store: store, pasteboard: pasteboard)

        for marker in SensitivePasteboard.markerTypes {
            declare("alpha-bravo", marker: marker, on: pasteboard)
            XCTAssertTrue(SensitivePasteboard.containsMarker(pasteboard), marker.rawValue)
            let changeCount = pasteboard.changeCount
            monitor.poll(sourceApplication: nil)
            monitor.poll(sourceApplication: nil)
            XCTAssertTrue(store.items.isEmpty, marker.rawValue)
            XCTAssertEqual(pasteboard.changeCount, changeCount, marker.rawValue)
        }

        declare("visible note", marker: nil, on: pasteboard)
        XCTAssertFalse(SensitivePasteboard.containsMarker(pasteboard))
        monitor.poll(sourceApplication: nil)
        XCTAssertEqual(store.items.map(\.fullText), ["visible note"])
    }

    func testConcealedMarkerConsumesChangeCount() throws {
        let (directory, defaults) = try fixture()
        let store = ClipFlowStore(storageDirectory: directory, defaults: defaults)
        defer { store.flushPendingPersistenceForTests() }
        store.ingestCopiedText("private note", sourceApp: "Passwords", sourceBundleID: "com.apple.Passwords")
        let capturedAt = try XCTUnwrap(store.items.first?.capturedAt)

        let pasteboard = NSPasteboard.withUniqueName()
        defer { pasteboard.releaseGlobally() }
        let monitor = ClipboardMonitor(store: store, pasteboard: pasteboard)
        let clock = TestClock(capturedAt.addingTimeInterval(299))
        monitor.now = { clock.date }
        monitor.lastPurgeAt = clock.date

        declare("alpha-bravo", marker: SensitivePasteboard.concealedType, on: pasteboard)
        monitor.poll(sourceApplication: nil)
        XCTAssertEqual(store.items.map(\.fullText), ["private note"])

        // Past expiry, but still inside the purge interval. A consumed change count
        // must not purge; leaving lastChangeCount stale would treat every poll as new.
        clock.date = capturedAt.addingTimeInterval(301)
        monitor.poll(sourceApplication: nil)
        XCTAssertEqual(store.items.map(\.fullText), ["private note"])

        monitor.lastPurgeAt = clock.date.addingTimeInterval(-ClipFlowMotion.clipboardPurgeInterval)
        monitor.poll(sourceApplication: nil)
        XCTAssertTrue(store.items.isEmpty)
    }

    func testPasswordManagerBundleIDsDriveExclusionAndSensitivity() throws {
        let expected = [
            "com.apple.keychainaccess",
            "com.apple.Passwords",
            "com.agilebits.onepassword7",
            "com.1password.1password",
            "com.bitwarden.desktop",
            "com.lastpass.LastPass",
            "com.lastpass.lastpassmacdesktop",
            "com.lastpass.lastpass-electron",
            "org.keepassx.keepassxc",
            "org.keepassxc.keepassxc",
            "com.dashlane.Dashlane",
            "in.sinew.Enpass-Desktop",
            "in.sinew.Enpass-Desktop.App",
            "me.proton.pass.electron",
            "com.nordsec.nordpass",
            "com.keepersecurity.passwordmanager",
            "com.markmcguill.strongbox.mac.pro",
            "com.hicknhacksoftware.MacPass",
            "com.SiberSystems.RoboForm",
            "com.sibersystems.RoboFormMac"
        ]
        XCTAssertEqual(PasswordManagerApps.bundleIDs, expected)
        XCTAssertEqual(Set(PasswordManagerApps.bundleIDs).count, PasswordManagerApps.bundleIDs.count)

        let (directory, defaults) = try fixture()
        let store = ClipFlowStore(storageDirectory: directory, defaults: defaults)
        defer { store.flushPendingPersistenceForTests() }
        XCTAssertEqual(store.excludedBundleIDs, PasswordManagerApps.bundleIDs)

        for bundleID in PasswordManagerApps.bundleIDs {
            XCTAssertTrue(PasswordManagerApps.contains(bundleID), bundleID)
            XCTAssertTrue(store.isExcluded(bundleID: bundleID), bundleID)
            let item = ClipboardClassifier.makeItem(
                text: "hello",
                sourceApp: "Manager",
                sourceBundleID: bundleID,
                autoProtectSecrets: false,
                existingItem: nil
            )
            XCTAssertEqual(item.privacy, .vault, bundleID)
        }

        let image = ClipboardClassifier.makeImageItem(
            imageFilename: "shot.png",
            imageSignature: "sig",
            imageSize: CGSize(width: 4, height: 4),
            sourceApp: "KeePassXC",
            sourceBundleID: "org.keepassxc.keepassxc",
            existingItem: nil
        )
        XCTAssertEqual(image.privacy, .vault)

        let plain = ClipboardClassifier.makeItem(
            text: "hello",
            sourceApp: "Safari",
            sourceBundleID: "com.apple.Safari",
            autoProtectSecrets: false,
            existingItem: nil
        )
        XCTAssertEqual(plain.privacy, .standard)
        XCTAssertFalse(PasswordManagerApps.contains("com.apple.Safari"))
        XCTAssertFalse(PasswordManagerApps.contains(nil))
        XCTAssertFalse(store.isExcluded(bundleID: "com.apple.Safari"))
        XCTAssertFalse(store.isExcluded(bundleID: nil))

        store.updateExcludedApps(from: "com.example.editor")
        XCTAssertEqual(store.excludedBundleIDs, ["com.example.editor"])
        XCTAssertTrue(store.isExcluded(bundleID: "com.example.editor"))
        XCTAssertTrue(store.isExcluded(bundleID: "org.keepassxc.keepassxc"))
        XCTAssertFalse(store.isExcluded(bundleID: "com.apple.Safari"))
        store.resetExcludedAppsToDefaults()
        XCTAssertEqual(store.excludedBundleIDs, PasswordManagerApps.bundleIDs)
    }

    func testSavedExclusionListStillSkipsPasswordManagers() throws {
        let (directory, defaults) = try fixture()
        defaults.set(["com.apple.keychainaccess"], forKey: "excludedBundleIDs")
        let store = ClipFlowStore(storageDirectory: directory, defaults: defaults)
        defer { store.flushPendingPersistenceForTests() }

        XCTAssertEqual(store.excludedBundleIDs, ["com.apple.keychainaccess"])
        for bundleID in PasswordManagerApps.bundleIDs {
            XCTAssertTrue(store.isExcluded(bundleID: bundleID), bundleID)
        }
        XCTAssertFalse(store.isExcluded(bundleID: "com.apple.Safari"))
        XCTAssertEqual(
            store.effectiveExcludedBundleIDs,
            Set(store.excludedBundleIDs).union(PasswordManagerApps.bundleIDs)
        )
    }
}

private final class TestClock: @unchecked Sendable {
    var date: Date
    init(_ date: Date) { self.date = date }
}
